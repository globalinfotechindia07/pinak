CREATE TABLE IF NOT EXISTS coupons (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    headline VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    badge_text VARCHAR(50) NOT NULL,
    discount_type VARCHAR(30) NOT NULL DEFAULT 'PERCENTAGE',
    discount_value NUMERIC(10, 2) NOT NULL,
    max_discount NUMERIC(10, 2),
    min_bill_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    partner_bank VARCHAR(100) DEFAULT 'ALL',
    payment_method_required VARCHAR(50) DEFAULT 'ANY',
    terms TEXT NOT NULL,
    store_id UUID,
    merchant_id UUID,
    category_id UUID,
    usage_limit_total INT DEFAULT 10000,
    usage_limit_per_user INT DEFAULT 10,
    current_usage_count INT DEFAULT 0,
    valid_from TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    valid_to TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT (NOW() + INTERVAL '365 days'),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_auto_applicable BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_coupons_code ON coupons(code);
CREATE INDEX IF NOT EXISTS idx_coupons_active ON coupons(is_active);
CREATE INDEX IF NOT EXISTS idx_coupons_store_id ON coupons(store_id);

